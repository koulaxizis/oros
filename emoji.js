// ============================================================
// orOS — emoji.js (Emoji picker, shell component, v1.0.0)
// ------------------------------------------------------------
// A shell component, like cliphist.js: it runs IN the shell document.
// shell.js calls attach() once at boot and refresh() after a language
// change. A bundle without this file draws exactly what it drew before.
//
// Chris 2026-11-15 22:32 (clipboard history thread, wave W3): a quick
// emoji picker; 22:33: every orOS shortcut on Ctrl+Alt+Shift, so it is
// Ctrl+Alt+Shift+. (SC_DEFS { id: "emoji", code: "Period" }), and the
// Quick settings button "Emoji".
//
//   • The list (emoji/data.js, generated by .github/scripts/emoji-data.js
//     from unicode-emoji-json and the Unicode CLDR annotations) loads
//     the first time the picker opens, never at boot.
//   • Dialog #emoji-dlg (centered, R32): a search box (English, Greek
//     and German names and words; every word must match, case, accents
//     and final sigma ignored), tabs for Recent and the nine groups, a
//     grid of emoji. Arrow keys move in the grid; Enter or a tap picks.
//   • A pick goes into the last text field the person was in, in the
//     app on screen (orosClip.insert, cliphist.js: never a password or
//     one-time code field), at its caret, and the picker stays open for
//     more; with no such field it is copied (toast) and the picker
//     closes. Escape closes it and the field gets the focus back.
//   • Recent: device-local oros-emoji-recent = { v:1, list:[emoji…] }
//     (at most 32, newest first), never synced, not in exports, removed
//     by the factory-reset oros-* sweep; nothing is added to it while
//     Sensitive work is on.
//
// Pure logic is unit-tested in node (tests/emoji.test.js).
// ============================================================
(function (root) {
  "use strict";

  var VER = "1.0.0";
  var RECENT_KEY = "oros-emoji-recent";
  var MAX_RECENT = 32;
  var MAX_HITS = 200;
  var GROUPS = ["smileys", "people", "nature", "food", "travel", "activities", "objects", "symbols", "flags"];
  var LANG_COL = { en: 1, el: 2, de: 3 };

  // i18n-inline-ok: the Greek final sigma in fold() is data, not a text to translate.
  // ---------- 1. Model (pure) ----------
  function fold(x) {
    return String(x || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
      .replace(/ς/g, "σ").replace(/ß/g, "ss");
  }
  // OROS_EMOJI → [{ id, list:[{ e, n:[en, el, de], f: folded words }] }]
  function rows(data) {
    if (!data || data.v !== 1 || !Array.isArray(data.groups)) return [];
    return data.groups.map(function (g) {
      return { id: String(g.id), list: String(g.rows || "").split("\n").filter(Boolean).map(function (r) {
        var c = r.split("\t");
        return { e: c[0], n: [c[1] || "", c[2] || "", c[3] || ""], f: fold([c[1], c[2], c[3], c[4]].join(" ")) };
      }) };
    });
  }
  // Every word of the query at the start of a word of the emoji (so
  // "cat" finds 🐱, not "education").
  function search(groups, q, max) {
    var words = fold(q).split(/\s+/).filter(Boolean);
    if (!words.length) return [];
    var out = [];
    for (var i = 0; i < groups.length; i++) {
      var l = groups[i].list;
      for (var j = 0; j < l.length; j++) {
        var f = " " + l[j].f.replace(/[^\p{L}\p{N}]+/gu, " ") + " ";
        if (words.every(function (w) { return f.indexOf(" " + w) !== -1; })) {
          out.push(l[j]);
          if (out.length >= (max || MAX_HITS)) return out;
        }
      }
    }
    return out;
  }
  function nameOf(item, lang) {
    var n = item.n[LANG_COL[lang] ? LANG_COL[lang] - 1 : 0];
    return n || item.n[0];
  }
  function parseRecent(raw) {
    var o;
    try { o = typeof raw === "string" ? JSON.parse(raw) : raw; } catch (e) { return []; }
    if (!o || o.v !== 1 || !Array.isArray(o.list)) return [];
    var seen = {}, out = [];
    o.list.forEach(function (x) {
      if (typeof x !== "string" || !x || x.length > 32 || seen[x]) return;
      seen[x] = 1;
      out.push(x);
    });
    return out.slice(0, MAX_RECENT);
  }
  function addRecent(list, e) {
    return [e].concat(list.filter(function (x) { return x !== e; })).slice(0, MAX_RECENT);
  }
  // Grid keyboard: the next index for an arrow key, columns cols.
  function step(i, key, cols, n) {
    if (!n) return -1;
    var j = i;
    if (key === "ArrowRight") j = i + 1;
    else if (key === "ArrowLeft") j = i - 1;
    else if (key === "ArrowDown") j = i + cols;
    else if (key === "ArrowUp") j = i - cols;
    else if (key === "Home") j = 0;
    else if (key === "End") j = n - 1;
    return Math.max(0, Math.min(n - 1, j));
  }

  var model = { VER: VER, GROUPS: GROUPS, MAX_RECENT: MAX_RECENT, fold: fold, rows: rows, search: search,
                nameOf: nameOf, parseRecent: parseRecent, addRecent: addRecent, step: step };
  if (typeof module !== "undefined" && module.exports) module.exports = model;
  if (typeof document === "undefined") return;

  // ---------- 2. Shell side ----------
  var doc = document;
  var host = null, dlg = null, parts = null, data = null, loading = null, tab = "recent", lastFocus = null;

  function t(k, vars) {
    var s = typeof root.t === "function" ? root.t(k) : k;
    if (vars) Object.keys(vars).forEach(function (n) { s = s.split("{" + n + "}").join(String(vars[n])); });
    return s;
  }
  function call(fn) { try { return fn(); } catch (e) { return undefined; } }
  function el(tag, cls, text) {
    var e = doc.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function lang() { return (host && host.lang && call(host.lang)) || "en"; }
  function strictOn() { return !!call(function () { return root.orosStrict && root.orosStrict.level(); }); }
  function locked() { return !!call(function () { return root.orosLock && root.orosLock.isLocked(); }); }

  function recent() {
    try { return parseRecent(root.localStorage.getItem(RECENT_KEY)); } catch (e) { return []; }
  }
  function remember(e) {
    if (strictOn()) return;
    try { root.localStorage.setItem(RECENT_KEY, JSON.stringify({ v: 1, list: addRecent(recent(), e) })); } catch (x) {}
  }

  // emoji/data.js, once, on the first open.
  function loadData() {
    if (data) return Promise.resolve(data);
    if (root.OROS_EMOJI) { data = rows(root.OROS_EMOJI); return Promise.resolve(data); }
    if (loading) return loading;
    loading = new Promise(function (res, rej) {
      var s = doc.createElement("script");
      var v = (host && host.version && call(host.version)) || "";
      s.src = "emoji/data.js" + (v ? "?v=" + encodeURIComponent(v) : "");
      s.onload = function () { data = rows(root.OROS_EMOJI); res(data); };
      s.onerror = function () { loading = null; rej(new Error("emoji data")); };
      doc.head.appendChild(s);
    });
    return loading;
  }

  var CSS = [
    "#emoji-dlg { width: min(420px, calc(100vw - 24px)); height: min(520px, calc(100dvh - 32px)); box-sizing: border-box; padding: 0;",
    "  border: 1px solid var(--border); border-radius: 18px; background: var(--panel-bg, var(--bar-bg)); color: var(--text);",
    "  box-shadow: 0 10px 34px var(--shadow, rgba(0,0,0,.4)); font-size: 14px; }",
    "#emoji-dlg[open] { display: flex; flex-direction: column; }",
    "#emoji-dlg::backdrop { background: rgba(0,0,0,.25); }",
    "#emoji-dlg [hidden] { display: none !important; }",
    ".emo-head { display: flex; align-items: center; gap: 8px; padding: 10px 8px 6px 12px; }",
    ".emo-head input { flex: 1; min-width: 0; min-height: 40px; padding: 0 12px; border: 1px solid var(--border); border-radius: 999px;",
    "  background: transparent; color: var(--text); font: inherit; box-sizing: border-box; }",
    ".emo-head input:focus-visible { outline: 2px solid var(--accent); outline-offset: 1px; }",
    ".emo-x { width: 44px; height: 44px; flex: none; display: inline-flex; align-items: center; justify-content: center; border: none;",
    "  border-radius: 50%; background: transparent; color: var(--text); cursor: pointer; }",
    ".emo-x:hover, .emo-x:focus-visible { background: var(--accent-soft); outline: none; }",
    ".emo-x svg { width: 18px; height: 18px; }",
    ".emo-tabs { display: flex; gap: 2px; padding: 0 8px 6px; overflow-x: auto; scrollbar-width: none; flex: none; }",
    ".emo-tabs::-webkit-scrollbar { display: none; }",
    ".emo-tab { flex: none; width: 40px; height: 40px; border: none; border-radius: 10px; background: transparent; font-size: 20px;",
    "  line-height: 1; cursor: pointer; color: var(--text); }",
    ".emo-tab[aria-selected=\"true\"] { background: var(--accent-soft); box-shadow: inset 0 -3px 0 var(--accent); }",
    ".emo-tab:focus-visible { outline: 2px solid var(--accent); outline-offset: -2px; }",
    ".emo-note { margin: 2px 14px 6px; font-size: 12.5px; opacity: .8; min-height: 1.2em; }",
    ".emo-grid { flex: 1; min-height: 0; overflow-y: auto; padding: 0 8px 10px; display: grid;",
    "  grid-template-columns: repeat(auto-fill, minmax(44px, 1fr)); grid-auto-rows: 44px; gap: 2px; align-content: start; }",
    ".emo-cell { border: none; border-radius: 10px; background: transparent; font-size: 26px; line-height: 1; cursor: pointer; padding: 0;",
    "  font-family: 'Noto Color Emoji', 'Segoe UI Emoji', 'Apple Color Emoji', sans-serif; }",
    ".emo-cell:hover, .emo-cell:focus-visible { background: var(--accent-soft); outline: none; }",
    ".emo-cell:focus-visible { box-shadow: inset 0 0 0 2px var(--accent); }",
    ".emo-empty { grid-column: 1 / -1; padding: 16px 6px; opacity: .8; }"
  ].join("\n");
  var X_ICON = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M18 6 6 18M6 6l12 12"/></svg>';
  var TAB_ICON = { recent: "🕘", smileys: "😀", people: "👋", nature: "🐻", food: "🍕", travel: "🚗", activities: "⚽", objects: "💡", symbols: "❤️", flags: "🏁" };

  function injectCss() {
    if (doc.getElementById("emoji-css")) return;
    var st = doc.createElement("style");
    st.id = "emoji-css";
    st.textContent = CSS;
    doc.head.appendChild(st);
  }

  function build() {
    injectCss();
    dlg = el("dialog");
    dlg.id = "emoji-dlg";
    dlg.setAttribute("aria-label", t("emo.title"));
    var head = el("div", "emo-head");
    var q = el("input");
    q.type = "search";
    q.placeholder = t("emo.search");
    q.setAttribute("aria-label", t("emo.search"));
    q.setAttribute("autocomplete", "off");
    q.addEventListener("input", paint);
    q.addEventListener("keydown", function (e) {
      if (e.key === "Enter") { var f = parts.grid.querySelector(".emo-cell"); if (f) { e.preventDefault(); pick(f.textContent); } }
      else if (e.key === "ArrowDown") { var g = parts.grid.querySelector(".emo-cell"); if (g) { e.preventDefault(); g.focus(); } }
    });
    head.appendChild(q);
    var x = el("button", "emo-x");
    x.type = "button";
    x.innerHTML = X_ICON;
    x.setAttribute("aria-label", t("emo.close"));
    x.title = t("emo.close");
    x.addEventListener("click", close);
    head.appendChild(x);
    dlg.appendChild(head);
    var tabs = el("div", "emo-tabs");
    tabs.setAttribute("role", "tablist");
    tabs.setAttribute("aria-label", t("emo.groups"));
    ["recent"].concat(GROUPS).forEach(function (id) {
      var b = el("button", "emo-tab", TAB_ICON[id]);
      b.type = "button";
      b.setAttribute("role", "tab");
      b.setAttribute("data-g", id);
      b.title = t("emo.g." + id);
      b.setAttribute("aria-label", t("emo.g." + id));
      b.addEventListener("click", function () { tab = id; q.value = ""; paint(); parts.grid.scrollTop = 0; });
      tabs.appendChild(b);
    });
    dlg.appendChild(tabs);
    var note = el("p", "emo-note");
    note.setAttribute("role", "status");
    dlg.appendChild(note);
    var grid = el("div", "emo-grid");
    grid.setAttribute("role", "grid");
    grid.addEventListener("click", function (e) {
      var c = e.target.closest && e.target.closest(".emo-cell");
      if (c) pick(c.textContent);
    });
    grid.addEventListener("keydown", function (e) {
      var cells = [].slice.call(grid.querySelectorAll(".emo-cell"));
      var i = cells.indexOf(doc.activeElement);
      if (i < 0) return;
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); pick(cells[i].textContent); return; }
      var cols = Math.max(1, Math.round(grid.clientWidth / cells[0].getBoundingClientRect().width) || 1);
      var first = cells[0].getBoundingClientRect().top;
      cols = cells.filter(function (c) { return Math.abs(c.getBoundingClientRect().top - first) < 2; }).length || cols;
      var j = step(i, e.key, cols, cells.length);
      if (e.key === "ArrowUp" && i < cols) { e.preventDefault(); q.focus(); return; }
      if (j !== i && j >= 0) { e.preventDefault(); cells[j].focus(); }
    });
    dlg.appendChild(grid);
    dlg.addEventListener("click", function (e) { if (e.target === dlg) close(); });
    var me = dlg;
    dlg.addEventListener("close", function () { if (dlg === me) close(); });
    parts = { q: q, tabs: tabs, note: note, grid: grid };
    doc.body.appendChild(dlg);
  }

  function cell(item) {
    var b = el("button", "emo-cell", item.e);
    b.type = "button";
    var n = nameOf(item, lang());
    b.title = n;
    b.setAttribute("aria-label", n);
    return b;
  }

  function paint() {
    if (!dlg || !parts) return;
    var q = parts.q.value.trim();
    [].forEach.call(parts.tabs.children, function (b) {
      b.setAttribute("aria-selected", !q && b.getAttribute("data-g") === tab ? "true" : "false");
    });
    parts.grid.textContent = "";
    if (!data) { parts.note.textContent = t(loading ? "emo.loading" : "emo.fail"); return; }
    var list;
    if (q) {
      list = search(data, q);
      parts.note.textContent = list.length ? "" : t("emo.none");
    } else if (tab === "recent") {
      var byE = {};
      data.forEach(function (g) { g.list.forEach(function (it) { byE[it.e] = it; }); });
      list = recent().map(function (e) { return byE[e]; }).filter(Boolean);
      parts.note.textContent = list.length ? t("emo.g.recent") : t("emo.norecent");
    } else {
      var g = data.filter(function (x) { return x.id === tab; })[0];
      list = g ? g.list : [];
      parts.note.textContent = t("emo.g." + tab);
    }
    var target = call(function () { return root.orosClip && root.orosClip.field(); });
    if (!q && target && list.length) parts.note.textContent += " · " + t("emo.into", { app: target.name || t("emo.thisapp") });
    var frag = doc.createDocumentFragment();
    list.forEach(function (it) { frag.appendChild(cell(it)); });
    parts.grid.appendChild(frag);
  }

  function pick(e) {
    if (!e) return;
    remember(e);
    var C = root.orosClip, target = call(function () { return C && C.field(); });
    if (target) {
      var ok = call(function () { return C.insert(e, { keepOpen: true }); });
      if (ok === "close") { lastFocus = null; close(); call(function () { C.insert(e); }); return; }
      if (ok) { if (parts) parts.note.textContent = t("emo.added", { e: e }); return; }
    }
    copy(e);
  }
  function copy(e) {
    function done(ok) {
      if (ok) close();
      if (host && host.toast) host.toast(ok ? "ok" : "err", t(ok ? "emo.copied" : "emo.nocopy", { e: e }));
    }
    function legacy() {
      var ta = el("textarea");
      ta.value = e;
      ta.style.cssText = "position:fixed;left:-9999px;top:0;opacity:0";
      (dlg || doc.body).appendChild(ta);
      ta.select();
      var ok = false;
      try { ok = doc.execCommand("copy"); } catch (x) {}
      ta.remove();
      done(ok);
    }
    var cb = root.navigator && root.navigator.clipboard;
    if (cb && typeof cb.writeText === "function") cb.writeText(e).then(function () { done(true); }, legacy);
    else legacy();
  }

  function open() {
    if (locked()) return;
    if (dlg && dlg.open) { parts.q.focus(); return; }
    lastFocus = doc.activeElement;
    build();
    tab = recent().length ? "recent" : tab === "recent" ? "smileys" : tab;   // Recent first, as on a desktop
    paint();
    try { dlg.showModal(); } catch (e) { dlg.setAttribute("open", ""); }
    parts.q.focus();
    loadData().then(function () { paint(); }, function () { paint(); });
  }
  function close() {
    if (!dlg) return;
    var d = dlg;
    dlg = null; parts = null;
    if (d.open) { try { d.close(); } catch (e) { d.removeAttribute("open"); } }
    if (d.parentNode) d.parentNode.removeChild(d);
    var C = root.orosClip;
    if (lastFocus && lastFocus.focus && lastFocus.isConnected) call(function () { lastFocus.focus(); });
    call(function () { if (C && C.field()) C.focusField(); });
  }
  function isOpen() { return !!(dlg && dlg.open); }

  function attach(h) {
    if (host) return;
    host = h || {};
  }

  root.orosEmoji = {
    VER: VER,
    model: model,
    attach: attach,
    open: open,
    close: close,
    isOpen: isOpen,
    toggle: function () { if (isOpen()) close(); else open(); },
    refresh: function () { if (isOpen()) { close(); open(); } }
  };
})(typeof window !== "undefined" ? window : globalThis);
