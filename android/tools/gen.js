#!/usr/bin/env node
// Generates the parts of the Android project that mirror the web app
// manifest (manifest.webmanifest), the way Bubblewrap / PWABuilder do:
//   app/src/main/AndroidManifest.xml          (share target, file
//                                              handlers, shortcuts)
//   app/src/main/res/values/web_manifest.xml  (URLs, colours, share
//                                              target JSON)
//   app/src/main/res/xml/shortcuts.xml
// Run after changing manifest.webmanifest:  node android/tools/gen.js
// `node android/tools/gen.js --check` fails when the files are stale
// (tests/android.test.js runs it).

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const APP = path.join(__dirname, "..", "app", "src", "main");
const HOST = "useoros.online";

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
// Android string resources: escape XML, then quotes and apostrophes.
function resStr(s) {
  return esc(s).replace(/'/g, "\\'").replace(/&quot;/g, '\\"');
}

function build(manifest) {
  const out = {};
  const st = manifest.share_target || null;
  const handlers = Array.isArray(manifest.file_handlers) ? manifest.file_handlers : [];
  const shortcuts = (Array.isArray(manifest.shortcuts) ? manifest.shortcuts : []).slice(0, 4);

  // ---- res/values/web_manifest.xml ----
  const v = [];
  v.push('<?xml version="1.0" encoding="utf-8"?>');
  v.push("<!-- Generated by android/tools/gen.js from manifest.webmanifest. Do not edit. -->");
  v.push("<resources>");
  v.push(`    <string name="appName">${resStr(manifest.name)}</string>`);
  v.push(`    <string name="launcherName">${resStr(manifest.short_name || manifest.name)}</string>`);
  v.push(`    <string name="launchUrl">https://${HOST}${esc(manifest.start_url || "/")}</string>`);
  v.push(`    <string name="hostName">${HOST}</string>`);
  v.push(`    <color name="colorPrimary">${manifest.theme_color}</color>`);
  v.push(`    <color name="colorPrimaryDark">${manifest.theme_color}</color>`);
  v.push(`    <color name="navigationColor">${manifest.theme_color}</color>`);
  v.push(`    <color name="navigationColorDark">${manifest.theme_color}</color>`);
  v.push(`    <color name="navigationDividerColor">#00000000</color>`);
  v.push(`    <color name="navigationDividerColorDark">#00000000</color>`);
  v.push(`    <color name="backgroundColor">${manifest.background_color}</color>`);
  v.push(`    <string name="orientation">${esc(manifest.orientation || "any")}</string>`);
  if (st) {
    const json = JSON.stringify({ action: st.action, method: st.method, enctype: st.enctype, params: st.params });
    v.push(`    <string name="shareTarget">${resStr(json)}</string>`);
  }
  handlers.forEach((h, i) => v.push(`    <string name="fileHandlingActionUrl${i}">https://${HOST}${esc(h.action)}</string>`));
  shortcuts.forEach((s, i) => {
    v.push(`    <string name="shortcut_name_${i}">${resStr(s.name)}</string>`);
    v.push(`    <string name="shortcut_short_name_${i}">${resStr(s.short_name || s.name)}</string>`);
  });
  v.push(`    <string name="assetStatements">[{\\"relation\\": [\\"delegate_permission/common.handle_all_urls\\"], \\"target\\": {\\"namespace\\": \\"web\\", \\"site\\": \\"https://${HOST}\\"}}]</string>`);
  v.push("</resources>");
  out["res/values/web_manifest.xml"] = v.join("\n") + "\n";

  // ---- res/xml/shortcuts.xml ----
  const sc = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by android/tools/gen.js. Do not edit. -->",
    '<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">'];
  shortcuts.forEach((s, i) => {
    sc.push(`    <shortcut android:shortcutId="shortcut${i}" android:enabled="true" android:icon="@mipmap/ic_launcher"`);
    sc.push(`        android:shortcutShortLabel="@string/shortcut_short_name_${i}" android:shortcutLongLabel="@string/shortcut_name_${i}">`);
    sc.push(`        <intent android:action="android.intent.action.MAIN" android:targetPackage="online.useoros.twa"`);
    sc.push(`            android:targetClass="online.useoros.twa.LauncherActivity" android:data="https://${HOST}${esc(s.url)}" />`);
    sc.push(`        <categories android:name="android.intent.category.LAUNCHER" />`);
    sc.push("    </shortcut>");
  });
  sc.push("</shortcuts>");
  out["res/xml/shortcuts.xml"] = sc.join("\n") + "\n";

  // ---- AndroidManifest.xml ----
  const shareMimes = [];
  if (st) {
    const files = (st.params && st.params.files) || [];
    files.forEach((f) => (f.accept || []).forEach((a) => { if (a.includes("/") && !shareMimes.includes(a)) shareMimes.push(a); }));
    if ((st.params.text || st.params.url || st.params.title) && !shareMimes.includes("text/plain")) shareMimes.push("text/plain");
  }
  const shareFilter = st ? `
            <intent-filter>
                <action android:name="android.intent.action.SEND" />${(st.params.files || []).length ? `
                <action android:name="android.intent.action.SEND_MULTIPLE" />` : ""}
                <category android:name="android.intent.category.DEFAULT" />${shareMimes.map((m) => `
                <data android:mimeType="${esc(m)}" />`).join("")}
            </intent-filter>` : "";
  const aliases = handlers.map((h, i) => `
        <activity-alias
            android:name="FileHandlingActivity${i}"
            android:targetActivity="LauncherActivity"
            android:exported="true">
            <meta-data android:name="android.support.customtabs.trusted.FILE_HANDLING_ACTION_URL"
                android:value="@string/fileHandlingActionUrl${i}" />
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="content" />${Object.keys(h.accept || {}).map((m) => `
                <data android:mimeType="${esc(m)}" />`).join("")}
            </intent-filter>
        </activity-alias>`).join("");

  out["AndroidManifest.xml"] = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/gen.js from manifest.webmanifest. Do not edit:
     change the template in android/tools/gen.js and run it again. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">

    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />
    <!-- Phone bridge (BR-PHONE): the "orOS" account in Contacts and Calendar. -->
    <uses-permission android:name="android.permission.READ_CONTACTS" />
    <uses-permission android:name="android.permission.WRITE_CONTACTS" />
    <uses-permission android:name="android.permission.READ_CALENDAR" />
    <uses-permission android:name="android.permission.WRITE_CALENDAR" />
    <uses-permission android:name="android.permission.READ_SYNC_SETTINGS" />
    <uses-permission android:name="android.permission.WRITE_SYNC_SETTINGS" />
    <uses-permission android:name="android.permission.GET_ACCOUNTS" android:maxSdkVersion="22" />

    <!-- Lets LauncherActivity see which browsers can run the TWA (Android 11+). -->
    <queries>
        <intent>
            <action android:name="android.support.customtabs.action.CustomTabsService" />
        </intent>
    </queries>

    <application
        android:name=".OrosApp"
        android:allowBackup="false"
        android:icon="@mipmap/ic_launcher"
        android:label="@string/appName"
        android:manageSpaceActivity="com.google.androidbrowserhelper.trusted.ManageDataLauncherActivity"
        android:supportsRtl="true"
        android:theme="@android:style/Theme.Translucent.NoTitleBar">

        <meta-data android:name="asset_statements" android:resource="@string/assetStatements" />
        <meta-data android:name="web_manifest_url" android:value="https://${HOST}/manifest.webmanifest" />
        <meta-data android:name="twa_generator" android:value="oros android/tools/gen.js" />

        <activity android:name="com.google.androidbrowserhelper.trusted.ManageDataLauncherActivity"
            android:exported="false"
            android:excludeFromRecents="true">
            <meta-data android:name="android.support.customtabs.trusted.MANAGE_SPACE_URL"
                android:value="@string/launchUrl" />
            <intent-filter>
                <action android:name="android.intent.action.APPLICATION_PREFERENCES" />
                <category android:name="android.intent.category.DEFAULT" />
            </intent-filter>
        </activity>

        <activity android:name=".LauncherActivity"
            android:alwaysRetainTaskState="true"
            android:label="@string/launcherName"
            android:exported="true">
            <meta-data android:name="android.support.customtabs.trusted.DEFAULT_URL" android:value="@string/launchUrl" />
            <meta-data android:name="android.support.customtabs.trusted.STATUS_BAR_COLOR" android:resource="@color/colorPrimary" />
            <meta-data android:name="android.support.customtabs.trusted.STATUS_BAR_COLOR_DARK" android:resource="@color/colorPrimaryDark" />
            <meta-data android:name="android.support.customtabs.trusted.NAVIGATION_BAR_COLOR" android:resource="@color/navigationColor" />
            <meta-data android:name="android.support.customtabs.trusted.NAVIGATION_BAR_COLOR_DARK" android:resource="@color/navigationColorDark" />
            <meta-data android:name="androix.browser.trusted.NAVIGATION_BAR_DIVIDER_COLOR" android:resource="@color/navigationDividerColor" />
            <meta-data android:name="androix.browser.trusted.NAVIGATION_BAR_DIVIDER_COLOR_DARK" android:resource="@color/navigationDividerColorDark" />
            <meta-data android:name="android.support.customtabs.trusted.SPLASH_IMAGE_DRAWABLE" android:resource="@drawable/splash" />
            <meta-data android:name="android.support.customtabs.trusted.SPLASH_SCREEN_BACKGROUND_COLOR" android:resource="@color/backgroundColor" />
            <meta-data android:name="android.support.customtabs.trusted.SPLASH_SCREEN_FADE_OUT_DURATION" android:value="300" />
            <meta-data android:name="android.support.customtabs.trusted.FILE_PROVIDER_AUTHORITY" android:value="\${applicationId}.fileprovider" />
            <meta-data android:name="android.app.shortcuts" android:resource="@xml/shortcuts" />
            <meta-data android:name="android.support.customtabs.trusted.FALLBACK_STRATEGY" android:value="customtabs" />${st ? `
            <meta-data android:name="android.support.customtabs.trusted.METADATA_SHARE_TARGET" android:resource="@string/shareTarget" />` : ""}
            <meta-data android:name="android.support.customtabs.trusted.SCREEN_ORIENTATION" android:value="@string/orientation" />
${shareFilter}
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>

            <intent-filter android:autoVerify="true">
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="https" android:host="\${hostName}" />
            </intent-filter>
        </activity>
${aliases}

        <activity android:name="com.google.androidbrowserhelper.trusted.FocusActivity" />
        <activity android:name="com.google.androidbrowserhelper.trusted.WebViewFallbackActivity"
            android:configChanges="orientation|screenSize" />

        <provider
            android:name="androidx.core.content.FileProvider"
            android:authorities="\${applicationId}.fileprovider"
            android:grantUriPermissions="true"
            android:exported="false">
            <meta-data android:name="android.support.FILE_PROVIDER_PATHS" android:resource="@xml/filepaths" />
        </provider>

        <service android:name=".DelegationService" android:enabled="true" android:exported="true">
            <intent-filter>
                <action android:name="android.support.customtabs.trusted.TRUSTED_WEB_ACTIVITY_SERVICE" />
                <category android:name="android.intent.category.DEFAULT" />
            </intent-filter>
        </service>
        <activity android:name="com.google.androidbrowserhelper.trusted.NotificationPermissionRequestActivity" />

        <!-- Phone bridge: the TWA postMessage channel (Chrome 115+). -->
        <service android:name="androidx.browser.customtabs.PostMessageService" android:exported="true" />

        <!-- Opened by the page from a tap ("intent://contacts#Intent;scheme=oros-permission;…"):
             asks Android for Contacts or Calendar access, then returns to orOS. -->
        <!-- Diagnostic builds: phone-bridge steps (app-icon shortcut). -->
        <activity android:name=".DiagActivity" android:exported="false"
            android:label="Bridge diagnostics"
            android:theme="@android:style/Theme.Material.Light" />

        <activity android:name=".PermissionActivity"
            android:exported="true"
            android:excludeFromRecents="true"
            android:noHistory="true"
            android:theme="@android:style/Theme.Translucent.NoTitleBar">
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="\${permissionScheme}" />
            </intent-filter>
        </activity>

        <!-- The "orOS" account: a stub authenticator plus sync adapters
             that only declare the account to Contacts and Calendar. The
             data is written by PhoneBridge when the page sends it. -->
        <service android:name=".AuthenticatorService" android:exported="false">
            <intent-filter>
                <action android:name="android.accounts.AccountAuthenticator" />
            </intent-filter>
            <meta-data android:name="android.accounts.AccountAuthenticator" android:resource="@xml/authenticator" />
        </service>
        <service android:name=".ContactsSyncService" android:exported="true">
            <intent-filter>
                <action android:name="android.content.SyncAdapter" />
            </intent-filter>
            <meta-data android:name="android.content.SyncAdapter" android:resource="@xml/sync_contacts" />
            <meta-data android:name="android.provider.CONTACTS_STRUCTURE" android:resource="@xml/contacts" />
        </service>
        <service android:name=".CalendarSyncService" android:exported="true">
            <intent-filter>
                <action android:name="android.content.SyncAdapter" />
            </intent-filter>
            <meta-data android:name="android.content.SyncAdapter" android:resource="@xml/sync_calendar" />
        </service>
    </application>
</manifest>
`;
  return out;
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "manifest.webmanifest"), "utf8"));
  const files = build(manifest);
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [rel, text] of Object.entries(files)) {
    const f = path.join(APP, rel);
    const cur = fs.existsSync(f) ? fs.readFileSync(f, "utf8") : null;
    if (cur === text) continue;
    if (check) stale.push(rel);
    else { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); console.log("wrote " + rel); }
  }
  if (check && stale.length) {
    console.error("Stale Android files (run node android/tools/gen.js): " + stale.join(", "));
    process.exit(1);
  }
}

if (require.main === module) main();
module.exports = { build };
