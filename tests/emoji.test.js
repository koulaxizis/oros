// Emoji picker (emoji.js, CLIP-1 W3): the model (data rows, search in
// English, Greek and German, recent list, grid keys), the generated
// data and the wiring in the shell, the page, Quick settings and the
// strings.
"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const path = require("path");
const fs = require("fs");

const ROOT = path.join(__dirname, "..");
const E = require(path.join(ROOT, "emoji.js"));
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
require(path.join(ROOT, "emoji/data.js"));
const DATA = E.rows(globalThis.OROS_EMOJI);

test("data: nine groups in order, well over a thousand emoji, three names each", () => {
  assert.deepEqual(DATA.map((g) => g.id), E.GROUPS);
  const all = DATA.reduce((n, g) => n + g.list.length, 0);
  assert.ok(all > 1500 && all < 2500, String(all));
  const smile = DATA[0].list[0];
  assert.equal(smile.e, "😀");
  assert.ok(smile.n[0] && smile.n[1] && smile.n[2], "English, Greek and German names");
  const seen = new Set();
  DATA.forEach((g) => g.list.forEach((it) => { assert.ok(!seen.has(it.e), it.e + " twice"); seen.add(it.e); }));
  assert.match(read("emoji/data.js"), /^\/\/ orOS — emoji\/data\.js: GENERATED by \.github\/scripts\/emoji-data\.js/);
});

test("search in English, Greek and German; words at the start of a word", () => {
  const has = (q, e) => E.search(DATA, q).some((it) => it.e === e);
  assert.ok(has("cat", "🐱"));
  assert.ok(has("γάτα", "🐱"));
  assert.ok(has("ΓΑΤΑ", "🐱"), "case and accents ignored");
  assert.ok(has("katze", "🐱"));
  assert.ok(has("καρδια", "❤️"));
  assert.ok(has("pizza", "🍕"));
  assert.ok(has("greece", "🇬🇷"));
  assert.ok(!has("ducation", "🎓"), "inside a word does not count");
  assert.equal(E.search(DATA, "   ").length, 0);
  assert.ok(E.search(DATA, "a", 5).length <= 5);
});

test("names follow the language; recent list is clean and capped", () => {
  const it = DATA[0].list[0];
  assert.equal(E.nameOf(it, "en"), it.n[0]);
  assert.equal(E.nameOf(it, "el"), it.n[1]);
  assert.equal(E.nameOf(it, "de"), it.n[2]);
  assert.equal(E.nameOf({ e: "x", n: ["only", "", ""] }, "el"), "only");
  assert.deepEqual(E.parseRecent('{"v":1,"list":["😀","😀",5,"🍕"]}'), ["😀", "🍕"]);
  assert.deepEqual(E.parseRecent("nope"), []);
  let r = [];
  for (let i = 0; i < 40; i++) r = E.addRecent(r, "e" + i);
  assert.equal(r.length, E.MAX_RECENT);
  assert.equal(r[0], "e39");
  assert.deepEqual(E.addRecent(["a", "b", "c"], "c"), ["c", "a", "b"]);
});

test("grid keys", () => {
  assert.equal(E.step(0, "ArrowRight", 8, 20), 1);
  assert.equal(E.step(0, "ArrowLeft", 8, 20), 0);
  assert.equal(E.step(3, "ArrowDown", 8, 20), 11);
  assert.equal(E.step(17, "ArrowDown", 8, 20), 19);
  assert.equal(E.step(11, "ArrowUp", 8, 20), 3);
  assert.equal(E.step(5, "End", 8, 20), 19);
  assert.equal(E.step(5, "Home", 8, 20), 0);
  assert.equal(E.step(0, "ArrowDown", 8, 0), -1);
});

test("wiring: Ctrl+Alt+Shift+. (code Period), page, Quick settings, field insert", () => {
  const shell = read("shell.js"), html = read("index.html");
  assert.match(shell, /\{ id: "emoji", code: "Period", label: "sc\.desc\.emoji"/);
  assert.match(shell, /code\.indexOf\("Key"\) !== 0 && code !== "Period"/);
  assert.match(shell, /if \(scCode\(SC_DEFS\[i\]\) === code\)/);
  assert.match(shell, /window\.orosEmoji\.attach\(/);
  assert.ok(html.indexOf('src="emoji.js') > html.indexOf('src="cliphist.js'));
  assert.ok(html.indexOf('src="emoji.js') < html.indexOf('src="shell.js'));
  assert.ok(!html.includes("emoji/data.js"), "the list loads on first open, not at boot");
  assert.match(read("qsettings.js"), /root\.orosEmoji\.open\(\)/);
  const clip = read("cliphist.js");
  assert.match(clip, /field: function \(\)/);
  assert.match(clip, /insert: function \(text, opts\)/);
});

test("strings in English, Greek and German; help; credits", () => {
  const keys = ["sc.desc.emoji", "qs.emoji", "emo.title", "emo.search", "emo.close", "emo.groups", "emo.loading", "emo.fail",
    "emo.none", "emo.norecent", "emo.into", "emo.thisapp", "emo.added", "emo.copied", "emo.nocopy"]
    .concat(["recent"].concat(E.GROUPS).map((g) => "emo.g." + g));
  const tr = read("translations.js"), de = read("i18n/de/shell.js");
  for (const k of keys) {
    assert.equal(tr.split('"' + k + '":').length - 1, 2, k + " in EN and EL");
    assert.ok(de.includes('"' + k + '":'), k + " in DE");
  }
  for (const f of ["help/topics/shortcuts.en.txt", "help/topics/shortcuts.el.txt", "i18n/de/help/topics/shortcuts.txt"]) {
    assert.ok(read(f).includes("[[Ctrl+Alt+Shift+.]]"), f);
  }
  assert.match(read("CREDITS.md"), /unicode-emoji-json/);
  assert.match(read("shell.js"), /k: "cr\.cldr-emoji"/);
  assert.ok(fs.existsSync(path.join(ROOT, "emoji/LICENSE-unicode-cldr.txt")));
});
